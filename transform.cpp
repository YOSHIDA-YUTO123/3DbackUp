//=================================================
// 移動量の減衰処理
//=================================================
void CVelocity::SetInertia(const float fcoef)
{
	// 0.0fに近づける
	m_move.x = LerpDest(0.0f, m_move.x, fcoef);
	m_move.z = LerpDest(0.0f, m_move.z, fcoef);
}
